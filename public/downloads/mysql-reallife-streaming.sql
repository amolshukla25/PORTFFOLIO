CREATE DATABASE IF NOT EXISTS portfolio_streaming CHARACTER SET utf8mb4;
USE portfolio_streaming;

CREATE TABLE IF NOT EXISTS plans (
 plan_id INT PRIMARY KEY,
 plan_name VARCHAR(40) NOT NULL,
 monthly_price DECIMAL(8,2) NOT NULL,
 max_streams INT NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS users (
 user_id INT PRIMARY KEY,
 user_name VARCHAR(80) NOT NULL,
 country VARCHAR(40) NOT NULL,
 plan_id INT NOT NULL,
 signup_date DATE NOT NULL,
 status VARCHAR(20) NOT NULL,
 FOREIGN KEY (plan_id) REFERENCES plans(plan_id),
 CHECK (status IN ('active','paused','cancelled'))
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS titles (
 title_id INT PRIMARY KEY,
 title_name VARCHAR(120) NOT NULL,
 kind VARCHAR(10) NOT NULL,
 genre VARCHAR(30) NOT NULL,
 release_year INT NOT NULL,
 age_rating VARCHAR(10) NOT NULL,
 CHECK (kind IN ('movie','series'))
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS watch_sessions (
 session_id INT PRIMARY KEY,
 user_id INT NOT NULL,
 title_id INT NOT NULL,
 watch_date DATE NOT NULL,
 minutes_watched INT NOT NULL,
 device VARCHAR(20) NOT NULL,
 completed INT NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(user_id),
 FOREIGN KEY (title_id) REFERENCES titles(title_id),
 CHECK (minutes_watched > 0)
) ENGINE=InnoDB;

