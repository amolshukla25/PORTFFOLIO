CREATE DATABASE IF NOT EXISTS portfolio_rides CHARACTER SET utf8mb4;
USE portfolio_rides;

CREATE TABLE IF NOT EXISTS drivers (
 driver_id INT PRIMARY KEY,
 driver_name VARCHAR(80) NOT NULL,
 city VARCHAR(60) NOT NULL,
 vehicle_type VARCHAR(20) NOT NULL,
 rating DECIMAL(3,2) NOT NULL,
 joined_on DATE NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS riders (
 rider_id INT PRIMARY KEY,
 rider_name VARCHAR(80) NOT NULL,
 city VARCHAR(60) NOT NULL,
 signup_date DATE NOT NULL,
 wallet_balance DECIMAL(10,2) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS trips (
 trip_id INT PRIMARY KEY,
 rider_id INT NOT NULL,
 driver_id INT,
 trip_date DATE NOT NULL,
 distance_km DECIMAL(6,2) NOT NULL,
 fare DECIMAL(10,2) NOT NULL,
 status VARCHAR(20) NOT NULL,
 payment_mode VARCHAR(20),
 surge_multiplier DECIMAL(4,2) NOT NULL,
 FOREIGN KEY (rider_id) REFERENCES riders(rider_id),
 FOREIGN KEY (driver_id) REFERENCES drivers(driver_id),
 CHECK (status IN ('completed','cancelled','no_driver'))
) ENGINE=InnoDB;

