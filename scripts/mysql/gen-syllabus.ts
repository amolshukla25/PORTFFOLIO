/**
 * Writes config/mysql/syllabus.ts — the small, client-safe summary of the
 * course (titles, minutes, problem counts) used by the course page, the
 * catalogue, navigation, sitemap and llms.txt. Run after editing a lesson:
 *   npm run mysql:syllabus
 */
import { writeFileSync } from "fs";
import { join } from "path";
import { MYSQL_LESSONS } from "../../config/mysql/index";
import { REAL_LIFE_MODULES } from "../../config/mysql/real-life";
import { estimateMinutes, lessonWordCount } from "../../config/mysql/estimate";

const MODULES = [
  { number: 1, title: "Foundations", description: "What a database is, installing MySQL and importing the practice shop." },
  { number: 2, title: "One table", description: "Filter, sort, transform and summarise the rows of a single table." },
  { number: 3, title: "Many tables", description: "Joins, subqueries, CTEs and set operations without double counting." },
  { number: 4, title: "Analysis", description: "Monthly reporting and window functions on small and large data." },
  { number: 5, title: "Build and change", description: "Design tables, change data safely, use views and indexes, and ship a capstone report." },
  ...REAL_LIFE_MODULES,
];

const syllabus = MYSQL_LESSONS.map((l) => ({
  slug: l.slug,
  shortTitle: l.shortTitle,
  title: l.title,
  summary: l.summary,
  module: l.module,
  minutes: estimateMinutes(l),
  words: lessonWordCount(l),
  questions: l.questions.length,
  quiz: l.quiz.length,
  dataset: l.dataset,
}));

const minutes = syllabus.reduce((s, l) => s + l.minutes, 0);
const facts = {
  lessons: syllabus.length,
  modules: MODULES.length,
  minutes,
  hours: Math.round(minutes / 30) / 2,
  problems: syllabus.reduce((s, l) => s + l.questions, 0),
  quizQuestions: syllabus.reduce((s, l) => s + l.quiz, 0),
  mysqlVersion: "8.0.16+ (8.4 LTS recommended)",
};

const body = `// GENERATED by scripts/mysql/gen-syllabus.ts — do not edit by hand.
import type { MysqlModule } from "./types";

export const MYSQL_MODULES: MysqlModule[] = ${JSON.stringify(MODULES, null, 2)};

export const MYSQL_SYLLABUS = ${JSON.stringify(syllabus, null, 2)} as const;

export const MYSQL_COURSE_FACTS = ${JSON.stringify(facts, null, 2)} as const;
`;
writeFileSync(join(__dirname, "..", "..", "config", "mysql", "syllabus.ts"), body);
console.log(facts);
