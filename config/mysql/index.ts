export function getMysqlLesson(slug: string) {
  const index = MYSQL_LESSONS.findIndex((l) => l.slug === slug);
  return index === -1 ? null : { lesson: MYSQL_LESSONS[index], index };
}

export interface StoredResult {
  sets: { columns: string[]; rows: (string | number | null)[][] }[];
  messages: string[];
  error?: { code: number; message: string };
}

/** Real MySQL 8 output for a snippet, generated by scripts/mysql/gen-results.py. */
export function mysqlResult(dataset: DatasetChoice, sql: string): StoredResult | null {
  const r = (results as Record<string, StoredResult & { where?: string }>)[snippetKey(dataset, sql)];
  if (!r) return null;
  return { sets: r.sets, messages: r.messages, ...(r.error ? { error: r.error } : {}) };
}
